export function makeBlock(type: BlockKind, id: string): Block {
  const tpl = defaultTemplates[type];
  return {
    id,
    type,
    label: type === "Hero" ? "Hero banner" : type,
    kicker: tpl.kicker,
    heading: tpl.heading,
    copy: tpl.copy,
    action: tpl.action,
    actionUrl: tpl.actionUrl,
    image: tpl.image,
    tone: tpl.tone,
    layout: tpl.layout,
    scale: tpl.scale,
    spacing: "comfortable",
    columns: tpl.columns,
    visible: true,
    items: tpl.items ? tpl.items.map((item) => ({ ...item })) : undefined,
  };
}

